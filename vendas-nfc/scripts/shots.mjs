// Capturas de tela (viewport de iPhone) com dados de demonstração, para revisão visual.
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const BASE = process.env.BASE_URL ?? "http://localhost:4173/";
const OUT = new URL("../e2e-artifacts/shots/", import.meta.url).pathname;
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: "pt-BR", timezoneId: "America/Sao_Paulo" });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const go = async (h) => { await page.goto(BASE + "#/" + h); await page.waitForTimeout(900); };
const shot = (n) => page.screenshot({ path: `${OUT}${n}.png` });
const scroll = async (y) => { await page.evaluate((y) => window.scrollTo(0, y), y); await page.waitForTimeout(450); };
await go("configuracoes");
await page.getByRole("radio", { name: "Ver demonstração" }).click();
await page.waitForTimeout(1500);
await go("inicio");
await page.getByRole("radio", { name: "Últimos 30 dias" }).click();
await page.waitForTimeout(800);
await shot("a1-inicio-topo");
await scroll(700); await shot("a2-inicio-kpis");
await scroll(1500); await shot("a3-inicio-rentabilidade");
await scroll(2700); await shot("a4-inicio-graficos");
await scroll(3600); await shot("a5-inicio-graficos2");
await go("rotas"); await shot("b1-rotas");
await page.locator("button", { hasText: "paradas" }).first().click(); await page.waitForTimeout(800);
await shot("b2-rota-detalhe");
await scroll(900); await shot("b3-rota-paradas");
await page.locator('button[aria-label^="Status:"]').first().click(); await page.waitForTimeout(500); await shot("b4-status-sheet");
await page.keyboard.press("Escape");
await go("vendas"); await page.getByRole("radio", { name: "Últimos 30 dias" }).click(); await page.waitForTimeout(500); await shot("c1-vendas");
await page.locator("button", { hasText: "Exemplo demo" }).first().click(); await page.waitForTimeout(600); await shot("c2-venda-detalhe");
await go("financas/resumo"); await page.getByRole("radio", { name: "Últimos 30 dias" }).click(); await page.waitForTimeout(500); await shot("d1-fin-resumo");
await go("financas/transporte"); await shot("d2-fin-transporte");
await go("financas/simulador"); await shot("d3-simulador"); await scroll(900); await shot("d4-simulador2");
await go("inteligencia"); await page.getByRole("radio", { name: "Últimos 30 dias" }).click(); await page.waitForTimeout(600); await shot("e1-intel"); await scroll(800); await shot("e2-intel-funil"); await scroll(1700); await shot("e3-intel-grupos");
await go("metas"); await shot("f1-metas");
await page.getByRole("button", { name: "Ações rápidas" }).click(); await page.waitForTimeout(400); await shot("g1-acoes");
await page.keyboard.press("Escape");
await go("configuracoes"); await page.getByRole("radio", { name: /Claro/ }).click(); await page.waitForTimeout(400);
await go("inicio"); await shot("h1-claro-inicio"); await scroll(700); await shot("h2-claro-kpis");
await go("configuracoes"); await page.getByRole("radio", { name: /Escuro/ }).click();
await browser.close();
console.log(errors.length ? "ERROS: " + errors.join("\n") : "ok, sem erros");
